def main():
    print("=" * 60)
    print("BUILDING MASTER ENTITIES (PHASE 1 & 2)")
    print("=" * 60)

    # 1. Save club_mapping.csv
    mapping_df = pd.DataFrame(CLUBS_DATA)
    mapping_path = os.path.join(MASTER_DIR, "club_mapping.csv")
    mapping_df.to_csv(mapping_path, index=False)
    print(f"1. Created {mapping_path}: {len(mapping_df)} clubs mapped across all sources.")

    # 2. Save master clubs.csv (Static Invariant Metadata)
    clubs_static_cols = [
        "club_id", "name_standard", "stadium_name", "stadium_capacity", "latitude", "longitude", "tm_club_id"
    ]
    clubs_df = mapping_df[clubs_static_cols].rename(columns={"name_standard": "club_name"})
    
    # Merge additional TM metadata: squad_size, avg_age, foreigners_percentage
    tm_clubs_raw = pd.read_csv(os.path.join(RAW_DIR, "transfermarkt", "epl_clubs.csv"))
    clubs_df = clubs_df.merge(
        tm_clubs_raw[["club_id", "squad_size", "average_age", "foreigners_percentage"]].rename(columns={"club_id": "tm_club_id"}),
        on="tm_club_id",
        how="left"
    ).drop(columns=["tm_club_id"])

    clubs_df["squad_size"] = clubs_df["squad_size"].fillna(28).astype(int)
    clubs_df["average_age"] = clubs_df["average_age"].fillna(25.5).round(1)
    clubs_df["foreigners_percentage"] = clubs_df["foreigners_percentage"].fillna(48.0).round(1)

    clubs_path = os.path.join(MASTER_DIR, "clubs.csv")
    clubs_df.to_csv(clubs_path, index=False)
    print(f"2. Created {clubs_path}: {len(clubs_df)} clubs with full static attributes.")


    # 3. Save master players.csv (Static Demographic Metadata & Career Profile)
    tm_players_raw = pd.read_csv(os.path.join(RAW_DIR, "transfermarkt", "epl_players.csv"))
    players_static = tm_players_raw[[
        "player_id", "first_name", "last_name", "name", "date_of_birth",
        "country_of_birth", "country_of_citizenship", "height_in_cm",
        "foot", "position", "sub_position",
        "highest_market_value_in_eur", "contract_expiration_date",
        "international_caps", "international_goals"
    ]].copy()
    players_static = players_static.rename(columns={
        "name": "full_name",
        "height_in_cm": "height_cm",
        "foot": "preferred_foot",
        "position": "main_position",
        "highest_market_value_in_eur": "peak_market_value_eur"
    })
    players_path = os.path.join(MASTER_DIR, "players.csv")
    players_static.to_csv(players_path, index=False)
    print(f"3. Created {players_path}: {len(players_static)} players with full demographic and career metadata.")

    # 4. Save master player_mapping.csv (Cross-source ID bridge across TM, FotMob, Understat, Opta, FPL)
    from scripts.build_player_mapping import main as build_player_mapping_main
    print("\n4. Building master player_mapping.csv...")
    build_player_mapping_main()

    print("\nSUCCESS: Master Entities (Clubs, Club Mapping, Players, Player Mapping) generated successfully!")


if __name__ == "__main__":
    main()

